//! Generic queries that calibrate the ranking across kinds of content.
//!
//! With EmbeddingGemma 2 a segment's cosine to a text query depends as much on what kind of
//! segment it is (and on the segment itself) as on the query: audio windows score higher
//! than photos against almost anything, and some segments (wind noise, a busy street) score
//! high against every query. So each segment is compared once with these probes, and a
//! query's cosine is ranked by how far it stands above that segment's usual cosine to a
//! query, over the square root of that cosine's spread
//! ([`crate::vindex::VectorIndex::set_probes`]).
//!
